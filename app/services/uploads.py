"""Safe file upload handling.

Files are validated by extension *and* content signature, renamed to random
identifiers and stored outside the static folder. They are only ever served
through ``files.download`` after an authorization check.
"""
import os
import uuid

from flask import current_app
from werkzeug.utils import secure_filename

from ..extensions import db
from ..models import Attachment
from .core import DomainError

IMAGE_TYPES = {
    "jpg": "image/jpeg", "jpeg": "image/jpeg", "png": "image/png", "webp": "image/webp",
}
DOCUMENT_TYPES = dict(IMAGE_TYPES, pdf="application/pdf")


def _signature_ok(ext, head):
    if ext in ("jpg", "jpeg"):
        return head.startswith(b"\xff\xd8\xff")
    if ext == "png":
        return head.startswith(b"\x89PNG\r\n\x1a\n")
    if ext == "webp":
        return head[:4] == b"RIFF" and head[8:12] == b"WEBP"
    if ext == "pdf":
        return head.startswith(b"%PDF-")
    return False


def upload_dir():
    path = current_app.config["UPLOAD_FOLDER"]
    os.makedirs(path, exist_ok=True)
    return path


def save_upload(file_storage, allowed=IMAGE_TYPES):
    """Validate and store an uploaded file. Returns metadata dict."""
    if file_storage is None or not file_storage.filename:
        raise DomainError("No file selected.")
    original = secure_filename(file_storage.filename) or "upload"
    ext = original.rsplit(".", 1)[-1].lower() if "." in original else ""
    if ext not in allowed:
        raise DomainError(f"File type not allowed. Allowed: {', '.join(sorted(set(allowed)))}.")
    limit = current_app.config["MAX_UPLOAD_MB"] * 1024 * 1024
    data = file_storage.stream.read(limit + 1)
    if len(data) > limit:
        raise DomainError(f"File is larger than {current_app.config['MAX_UPLOAD_MB']} MB.")
    if len(data) == 0:
        raise DomainError("The uploaded file is empty.")
    if not _signature_ok(ext, data[:16]):
        raise DomainError("The file content does not match its type.")
    stored = f"{uuid.uuid4().hex}.{ext}"
    with open(os.path.join(upload_dir(), stored), "wb") as fh:
        fh.write(data)
    return {
        "original_filename": original[:255],
        "stored_filename": stored,
        "content_type": allowed[ext],
        "size_bytes": len(data),
    }


def attach_files(files, entity_type, entity_id, user, caption=None):
    """Save every non-empty file in ``files`` as an Attachment."""
    files = [f for f in (files or []) if f and f.filename]
    if len(files) > 6:
        raise DomainError("At most 6 photos can be uploaded at once.")
    created = []
    for f in files:
        meta = save_upload(f, IMAGE_TYPES)
        att = Attachment(entity_type=entity_type, entity_id=entity_id, uploaded_by_id=user.id,
                         caption=caption, **meta)
        db.session.add(att)
        created.append(att)
    return created


def attachments_for(entity_type, entity_id):
    return (db.session.query(Attachment)
            .filter_by(entity_type=entity_type, entity_id=entity_id)
            .order_by(Attachment.id).all())


def file_path(stored_filename):
    # stored names are generated by us (uuid hex + ext); still guard traversal
    safe = secure_filename(stored_filename)
    if safe != stored_filename:
        raise DomainError("Invalid file name.")
    return os.path.join(upload_dir(), safe)
